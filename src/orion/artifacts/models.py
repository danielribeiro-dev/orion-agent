"""
O.R.I.O.N — Artifact Models
Typed metadata contracts for structured documents generated by the engine.

Inspired by the Antigravity CLI artifact system (ArtifactMetadata) and extended
with ORION-specific fields for dual-storage routing and lifecycle tracking.
"""

from __future__ import annotations

import uuid
from datetime import datetime, timezone
from enum import Enum
from pathlib import Path

from pydantic import BaseModel, Field


class StorageScope(str, Enum):
    """Determines where the artifact is persisted.

    GLOBAL — Written to ~/.orion/brain/<session_id>/artifacts/
             Survives across projects and sessions.
    LOCAL  — Written to .orion/artifacts/ (relative to CWD / project root).
             Scoped to the current project workspace.
    BOTH   — Written to both locations (default for user-facing artifacts).
    """

    GLOBAL = "global"
    LOCAL = "local"
    BOTH = "both"


class ArtifactMetadata(BaseModel):
    """Metadata envelope for every artifact produced by ORION."""

    model_config = {"frozen": True}

    artifact_id: str = Field(default_factory=lambda: str(uuid.uuid4()))
    session_id: str = Field(description="ID of the engine session that created this artifact.")
    created_at: datetime = Field(
        default_factory=lambda: datetime.now(timezone.utc)
    )

    # Content descriptors
    filename: str = Field(description="Basename of the artifact file (e.g. 'plan.md').")
    summary: str = Field(
        description="Human-readable multi-line description of the artifact's contents and purpose."
    )

    # Presentation flags
    user_facing: bool = Field(
        default=True,
        description="If True, the artifact should be surfaced to the user in the CLI.",
    )
    request_feedback: bool = Field(
        default=False,
        description=(
            "If True and the artifact is executable (e.g. a plan), "
            "the CLI should present a [Proceed] confirmation prompt."
        ),
    )

    # Storage
    scope: StorageScope = Field(
        default=StorageScope.BOTH,
        description="Where to persist the artifact.",
    )

    # Filled in by ArtifactStore after writing
    global_path: Path | None = Field(
        default=None,
        description="Absolute path of the global copy (set by ArtifactStore).",
    )
    local_path: Path | None = Field(
        default=None,
        description="Absolute path of the local copy (set by ArtifactStore).",
    )


class Artifact(BaseModel):
    """A complete artifact: metadata + raw markdown content."""

    model_config = {"frozen": True}

    metadata: ArtifactMetadata
    content: str = Field(description="Raw markdown content of the artifact.")

    @property
    def artifact_id(self) -> str:
        return self.metadata.artifact_id

    @property
    def filename(self) -> str:
        return self.metadata.filename
